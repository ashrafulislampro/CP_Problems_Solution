void solve()
{
    int n, x;
    cin >> n;
    set<int> st;
    multiset<int> mls;
    for (int i = 0; i < n; i++)
    {
        cin >> x;
        mls.insert(x);
    }

    while(!mls.empty()){
        auto it = mls.begin();
        int val = *it;
        mls.erase(it);

        if(val <= n){
            if(!st.count(val)){
                st.insert(val);
            }
        }
    }   
}
