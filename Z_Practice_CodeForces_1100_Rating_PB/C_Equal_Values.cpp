void solve()
{
    int n;
    cin >> n;
    vll aa(n + 1);
    for (int i = 1; i <= n; i++)
        cin >> aa[i];

    ll mn_sum = 1e18;
    ll l = 1, r = 1;

    while (r <= n)
    {

        while (r <= n and aa[l] == aa[r])
            r++;

        ll total_sum = aa[l] * (l - 1 + n - r + 1);

        mn_sum = min(mn_sum, total_sum);
        l = r;
    }

    cout << mn_sum;
}
